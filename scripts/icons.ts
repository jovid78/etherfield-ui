// Copies the geometry of the icons listed below from Iconoir (MIT, https://iconoir.com) into src/icon-data.ts.
// Only listed icons are shipped. To add one: find its name on iconoir.com, add it here, run `pnpm icons`.
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const names = [
  // Controls
  'plus',
  'minus',
  'check',
  'xmark',
  'nav-arrow-down',
  'nav-arrow-up',
  'nav-arrow-left',
  'nav-arrow-right',
  'search',
  'upload',
  'page',
  'calendar',
  // Status
  'warning-circle',
  'warning-triangle',
  'info-circle',
  'check-circle',
  // 3D and game
  'cube',
  'axes',
  'hexagon',
  'dice-six',
] as const

// NOTE: Iconoir puts these on every shape. Icon sets them once on the <svg>, so the shapes inherit them.
const inherited = new Set(['stroke', 'stroke-linecap', 'stroke-linejoin'])
const tags = new Set(['path', 'circle', 'rect'])

// NOTE: iconoir's package.json doesn't export its icon files, so read them from node_modules directly.
const root = fileURLToPath(new URL('../node_modules/iconoir/', import.meta.url))
const folder = join(root, 'icons', 'regular')
const version: string = JSON.parse(
  readFileSync(join(root, 'package.json'), 'utf8'),
).version

const parse = (name: string) => {
  const svg = readFileSync(join(folder, `${name}.svg`), 'utf8')
  const inner = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
  const shapes = [...inner.matchAll(/<([a-zA-Z]+)\s([^>]*?)\/?>/g)].map(
    ([, tag = '', body = '']) => {
      if (!tags.has(tag))
        throw new Error(`${name}: <${tag}> is not supported, pick another icon`)
      const attributes = Object.fromEntries(
        [...body.matchAll(/([a-z-]+)="([^"]*)"/g)]
          .filter(
            ([, key = '', value]) =>
              !(
                inherited.has(key) &&
                (key !== 'stroke' || value === 'currentColor')
              ),
          )
          .map(([, key, value]) => [key, value]),
      )
      return [tag, attributes] as const
    },
  )
  return shapes
}

const data = Object.fromEntries(names.map(name => [name, parse(name)]))
writeFileSync(
  new URL('../src/icon-data.ts', import.meta.url),
  `// Generated by scripts/icons.ts from iconoir ${version} (MIT, https://iconoir.com). Do not edit.\n` +
    `export const icons = ${JSON.stringify(data, null, 2)} as const\n`,
)
console.log(`Wrote ${names.length} icons from iconoir ${version}`)
